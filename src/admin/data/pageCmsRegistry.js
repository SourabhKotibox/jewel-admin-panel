function fromSecondary(key, cfg) {
  return {
    fieldGroups: cfg.fieldGroups,
    defaultFields: cfg.defaultFields,
    defaultSectionLayout: cfg.defaultSectionLayout,
    builtinSections: cfg.builtinSections,
    normalize: cfg.normalizeSectionLayout,
    extract: cfg.extractSectionLayout,
    adminGroupToSectionId: cfg.adminGroupToSectionId,
    isHidden: cfg.isSectionHidden,
    createCustom: cfg.createCustomSection,
    fieldsToCms: cfg.fieldsToCms,
    cmsToFields: cfg.cmsToFields,
    tip: null,
    previewKind: key,
  };
}

